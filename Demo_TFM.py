# ── Celda 9: Proceso reverse — predicción de cadenas laterales
@torch.no_grad()
def predict_side_chains(model, graph, device, n_steps=20):
    """
    Aplica el proceso reverse de difusión torsional para predecir
    los ángulos chi de las cadenas laterales.

    Parte de ángulos aleatorios uniformes (ruido total, t=T) y
    aplica n_steps pasos de denoising usando ChiGNN para recuperar
    los ángulos originales χ_0.

    Parámetros
    ----------
    model   : ChiGNN entrenado
    graph   : Data — grafo de la proteína
    device  : torch.device
    n_steps : int — pasos de denoising (20 es suficiente para la demo)

    Retorna
    -------
    torch.Tensor [N_residuos, 4] — ángulos chi predichos en radianes
    """
    model.eval()
    graph = graph.to(device)
    N     = graph.num_nodes

    # Inicializar con ruido puro: ángulos uniformes en [-π, π]
    # Esto simula t=T, el punto de partida del proceso reverse.
    chi_t = torch.tensor(
        np.random.uniform(-np.pi, np.pi, size=(N, 4)),
        dtype=torch.float, device=device
    )

    # Pasos de tiempo decrecientes: T → 1
    timesteps = torch.linspace(T, 1, n_steps).long()

    for i, t_int in enumerate(timesteps):
        t_val  = t_int.item()
        t_norm = torch.full((N, 1), t_val / T, dtype=torch.float, device=device)

        # ChiGNN predice χ_0 a partir de los ángulos ruidosos χ_t
        chi_0_pred = model(
            x          = graph.x,
            aa_type    = graph.aa_type,
            edge_index = graph.edge_index,
            chi_noisy  = chi_t,
            t_node     = t_norm
        )

        # Excepto en el último paso, re-añadimos ruido de nivel t-1
        # (simulación de la cadena de Markov inversa, algoritmo DDIM)
        if t_val > 1:
            t_prev     = t_val - (T / n_steps)
            kappa_prev = get_kappa(int(t_prev))
            mask_all   = torch.ones(N, 4, dtype=torch.bool)
            chi_t      = von_mises_sample(
                torch.rad2deg(chi_0_pred).cpu(), kappa_prev
            ).to(device)
            # Convertir de vuelta a radianes para la siguiente iteración
            chi_t      = torch.deg2rad(chi_t)
        else:
            chi_t = chi_0_pred

    return chi_t.cpu()   # [N, 4] en radianes

print("🔄 Ejecutando proceso reverse (predicción de cadenas laterales)...")
chi_pred = predict_side_chains(model, graph, device, n_steps=20)
chi_pred_deg = torch.rad2deg(chi_pred)

