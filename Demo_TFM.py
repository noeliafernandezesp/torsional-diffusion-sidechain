# ── Celda 12: Extraer ángulos chi experimentales del PDB ─────
# El archivo PDB contiene las posiciones reales de todos los átomos,
# lo que permite calcular los ángulos chi de referencia con Biopython
# y compararlos directamente con las predicciones de ChiGNN.

def extract_chi_from_pdb(pdb_path: str):
    """
    Extrae los ángulos chi reales de un archivo PDB usando Biopython.
    Devuelve un tensor [N_residuos, 4] en grados, con NaN donde el
    ángulo no existe o no puede calcularse por falta de átomos.

    Los ángulos se calculan usando calc_dihedral() de Biopython,
    idéntico al procedimiento del pipeline de entrenamiento.
    """
    parser    = Bio.PDB.PDBParser(QUIET=True)
    structure = parser.get_structure("prot", pdb_path)

    # Definición de los átomos que forman cada ángulo chi por ángulo
    # (átomo delta = extremo del diedro en ese nivel)
    DELTA_ATOMS = {
        1: ['CG', 'CG1', 'OG', 'SG', 'OG1'],   # χ₁
        2: ['CD', 'CD1', 'ND1', 'OD1', 'SD'],   # χ₂
        3: ['CE', 'NE', 'OE1', 'NZ'],            # χ₃
        4: ['CZ', 'NH1', 'NZ'],                  # χ₄
    }

    chi_real = []

    for model_pdb in structure:
        for chain in model_pdb:
            for residue in sorted(chain.get_residues(), key=lambda r: r.get_id()[1]):
                if residue.get_id()[0] != ' ':
                    continue
                atom_names = {a.get_name() for a in residue}
                if not {'N', 'CA', 'C'}.issubset(atom_names):
                    continue

                angles = [np.nan, np.nan, np.nan, np.nan]

                if 'CB' in atom_names:
                    # χ₁: N – CA – CB – CG
                    gamma = next((residue[a] for a in DELTA_ATOMS[1] if a in atom_names), None)
                    if gamma:
                        angles[0] = np.degrees(Bio.PDB.calc_dihedral(
                            residue['N'].get_vector(),
                            residue['CA'].get_vector(),
                            residue['CB'].get_vector(),
                            gamma.get_vector()
                        ))

                    # χ₂: CA – CB – CG – CD
                    if gamma:
                        delta = next((residue[a] for a in DELTA_ATOMS[2] if a in atom_names), None)
                        if delta:
                            angles[1] = np.degrees(Bio.PDB.calc_dihedral(
                                residue['CA'].get_vector(),
                                residue['CB'].get_vector(),
                                gamma.get_vector(),
                                delta.get_vector()
                            ))

                            # χ₃: CB – CG – CD – CE
                            epsilon = next((residue[a] for a in DELTA_ATOMS[3] if a in atom_names), None)
                            if epsilon:
                                angles[2] = np.degrees(Bio.PDB.calc_dihedral(
                                    residue['CB'].get_vector(),
                                    gamma.get_vector(),
                                    delta.get_vector(),
                                    epsilon.get_vector()
                                ))

                                # χ₄: CG – CD – CE – CZ
                                zeta = next((residue[a] for a in DELTA_ATOMS[4] if a in atom_names), None)
                                if zeta:
                                    angles[3] = np.degrees(Bio.PDB.calc_dihedral(
                                        gamma.get_vector(),
                                        delta.get_vector(),
                                        epsilon.get_vector(),
                                        zeta.get_vector()
                                    ))

                chi_real.append(angles)
        break

    return np.array(chi_real, dtype=np.float32)   # [N, 4] en grados, con NaN

