# ── Celda 4: Constantes del modelo ───────────────────────────
# Deben coincidir EXACTAMENTE con los valores usados en el entrenamiento.
# Cambiar estos valores sin re-entrenar produciría predicciones incorrectas.

T         = 100      # Pasos totales de difusión
KAPPA_MAX = 10.0     # Concentración máxima de Von Mises (t=0, sin ruido)
KAPPA_MIN = 0.01     # Concentración mínima de Von Mises (t=T, ruido total)

# Mapeo de aminoácidos a índice entero (idéntico al notebook de entrenamiento)
AA_TO_IDX = {
    'ALA': 0,  'ARG': 1,  'ASN': 2,  'ASP': 3,  'CYS': 4,
    'GLN': 5,  'GLU': 6,  'GLY': 7,  'HIS': 8,  'ILE': 9,
    'LEU': 10, 'LYS': 11, 'MET': 12, 'PHE': 13, 'PRO': 14,
    'SER': 15, 'THR': 16, 'TRP': 17, 'TYR': 18, 'VAL': 19
}

def get_kappa(t: int) -> float:
    """
    Devuelve la concentración κ en el paso t.
    Schedule lineal: t=0 → κ_max (sin ruido), t=T → κ_min (ruido total).
    """
    return KAPPA_MAX - (KAPPA_MAX - KAPPA_MIN) * (t / T)

def von_mises_sample(mu: torch.Tensor, kappa: float) -> torch.Tensor:
    """
    Muestrea ángulos de Von Mises VM(μ, κ) usando NumPy.
    Devuelve tensor en [-π, π].
    """
    samples_np = np.random.vonmises(mu.cpu().numpy(), kappa)
    return torch.tensor(samples_np, dtype=torch.float)

# ── Celda 5: Arquitectura ChiGNN ─────────────────────────────
# Definición IDÉNTICA a la del notebook de entrenamiento.
# Cualquier diferencia (hidden_dim, n_layers, aa_embed) haría
# incompatible la carga de pesos del checkpoint.

class ChiGNN(nn.Module):
    """
    Red Neuronal de Grafos para denoising de ángulos chi.
    Versión 'lite' inspirada en DiffPack, diseñada para Google Colab T4.

    Entrada por nodo: coordenadas backbone (9) + embedding aminoácido (16)
                    + sin/cos de χ_t (8) + paso de tiempo t (1) = 34 features
    Salida por nodo: 4 ángulos chi predichos en [-π, π]
    """

    def __init__(self, hidden_dim=128, n_layers=4, aa_embed=16):
        super().__init__()
        self.hidden_dim = hidden_dim
        self.n_layers   = n_layers
        self.aa_embedding = nn.Embedding(21, aa_embed)

        input_dim = 9 + aa_embed + 8 + 1   # backbone + aa + chi_enc + t

        self.input_proj = nn.Sequential(nn.Linear(input_dim, hidden_dim), nn.SiLU())

        self.conv_layers = nn.ModuleList([GCNConv(hidden_dim, hidden_dim) for _ in range(n_layers)])
        self.norms       = nn.ModuleList([nn.BatchNorm1d(hidden_dim)       for _ in range(n_layers)])
        self.acts        = nn.ModuleList([nn.SiLU()                        for _ in range(n_layers)])

        self.output_head = nn.Sequential(
            nn.Linear(hidden_dim, hidden_dim // 2), nn.SiLU(),
            nn.Linear(hidden_dim // 2, 4)
        )

    def encode_angles(self, chi):
        """Codifica ángulos como pares (sin, cos) para respetar periodicidad."""
        return torch.cat([torch.sin(chi), torch.cos(chi)], dim=-1)

    def forward(self, x, aa_type, edge_index, chi_noisy, t_node):
        aa_emb    = self.aa_embedding(aa_type)
        chi_enc   = self.encode_angles(chi_noisy)
        node_feat = torch.cat([x, aa_emb, chi_enc, t_node], dim=-1)
        h         = self.input_proj(node_feat)

        for conv, norm, act in zip(self.conv_layers, self.norms, self.acts):
            h = h + act(norm(conv(h, edge_index)))   # Conexión residual

        return torch.tanh(self.output_head(h)) * torch.pi   # Salida en [-π, π]

