# ── Celda 8: Parsear el PDB y construir el grafo ─────────────
def pdb_to_graph(pdb_path: str) -> Data:
    """
    Lee un archivo PDB y construye el grafo de PyTorch Geometric
    que ChiGNN espera como input.

    Solo se usan las coordenadas del backbone (N, Cα, C).
    Las cadenas laterales se ignoran completamente — el modelo
    las predecirá desde cero.

    Parámetros
    ----------
    pdb_path : str — ruta al archivo .pdb

    Retorna
    -------
    torch_geometric.data.Data — grafo listo para inferencia
    """
    parser    = Bio.PDB.PDBParser(QUIET=True)
    structure = parser.get_structure("prot", pdb_path)

    coords_list = []   # Coordenadas backbone por residuo
    aa_list     = []   # Tipo de aminoácido por residuo
    skipped     = 0    # Residuos descartados (sin backbone completo)

    for model_pdb in structure:
        for chain in model_pdb:
            residues = sorted(chain.get_residues(), key=lambda r: r.get_id()[1])
            for residue in residues:
                res_name = residue.get_resname().strip()

                # Ignorar heteroátomos (agua, ligandos, etc.)
                if residue.get_id()[0] != ' ':
                    continue

                # Verificar que el backbone está completo
                atom_names = {a.get_name() for a in residue}
                if not {'N', 'CA', 'C'}.issubset(atom_names):
                    skipped += 1
                    continue

                # Extraer coordenadas de los tres átomos del backbone
                n_vec  = residue['N'].get_vector().get_array()
                ca_vec = residue['CA'].get_vector().get_array()
                c_vec  = residue['C'].get_vector().get_array()

                # El vector de features del nodo: [N_x, N_y, N_z, CA_x, ..., C_z]
                coords_list.append(np.concatenate([n_vec, ca_vec, c_vec]))
                aa_list.append(AA_TO_IDX.get(res_name, 20))   # 20 = desconocido

        break  # Solo usamos el primer modelo del PDB (por si hay NMR ensembles)

    if len(coords_list) == 0:
        raise ValueError("❌ No se encontraron residuos válidos en el PDB.")

    n_res = len(coords_list)

    # Construir aristas: grafo lineal bidireccional (cada residuo conectado
    # al anterior y al siguiente), replicando la topología del entrenamiento.
    src = list(range(n_res - 1)) + list(range(1, n_res))
    dst = list(range(1, n_res)) + list(range(n_res - 1))

    x          = torch.tensor(np.array(coords_list), dtype=torch.float)
    aa_type    = torch.tensor(aa_list, dtype=torch.long)
    edge_index = torch.tensor([src, dst], dtype=torch.long)

    # y e y_mask vacíos: el modelo predecirá los ángulos, no los conocemos
    y      = torch.zeros(n_res, 4, dtype=torch.float)
    y_mask = torch.zeros(n_res, 4, dtype=torch.bool)

    print(f"✅ Grafo construido:")
    print(f"   Residuos procesados : {n_res}")
    print(f"   Residuos omitidos   : {skipped} (backbone incompleto)")
    print(f"   Aristas (grafo)     : {edge_index.shape[1]}")

    return Data(x=x, aa_type=aa_type, edge_index=edge_index,
                y=y, y_mask=y_mask)

