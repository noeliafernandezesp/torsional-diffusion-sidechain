# Calcula las mismas métricas reportadas en el TFM (Capítulo 4)
# sobre la proteína de la demo:
#
#   · MAE circular:          error angular promedio respetando
#                             la periodicidad de los ángulos
#   · Recuperación ±20°:     % de predicciones con error < 20°
#   · Recuperación ±40°:     % de predicciones con error < 40°
#   · Estado rotamérico:     distribución predicha en g⁻ / t / g⁺
#
# NOTA: al ser una sola proteína, los valores pueden diferir
# de los del conjunto de test (597 proteínas). El resultado
# es orientativo y válido para ilustrar el funcionamiento
# del modelo durante la defensa.

def circular_mae(pred_deg: np.ndarray, real_deg: np.ndarray) -> float:
    """
    MAE circular en grados: mide la diferencia angular más corta
    entre predicción y valor real, ignorando la periodicidad.
    Equivalente a mean(min(|Δθ|, 360 - |Δθ|)).
    """
    diff = np.abs(pred_deg - real_deg) % 360
    diff = np.minimum(diff, 360 - diff)
    return float(np.mean(diff))

def recovery_rate(pred_deg: np.ndarray, real_deg: np.ndarray, tol: float) -> float:
    """
    Tasa de recuperación: % de predicciones con error circular < tol grados.
    """
    diff = np.abs(pred_deg - real_deg) % 360
    diff = np.minimum(diff, 360 - diff)
    return float(np.mean(diff < tol) * 100)

def rotamer_state(angle_deg: float) -> str:
    """
    Clasifica un ángulo χ₁ en su estado rotamérico canónico:
      g⁻ ≈ −60°  (gauche minus)
      t  ≈ 180°  (trans)
      g⁺ ≈ +60°  (gauche plus)
    """
    a = ((angle_deg + 180) % 360) - 180   # Normalizar a [-180, 180]
    if -120 <= a < 0:
        return "g⁻"
    elif a >= 120 or a < -120:
        return "t"
    else:
        return "g⁺"

