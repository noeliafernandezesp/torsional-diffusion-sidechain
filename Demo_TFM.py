# ── Celda 10: Visualización del resultado ────────────────────
def apply_chi1_to_pdb(pdb_path: str, chi_pred_deg: torch.Tensor) -> str:
    """
    Aplica los ángulos χ₁ predichos a la estructura y devuelve
    el PDB modificado como string para visualización con py3Dmol.

    Solo modifica χ₁ para mantener la visualización clara.
    La modificación geométrica rota el átomo Cγ alrededor del
    enlace Cα–Cβ para posicionarlo según el ángulo predicho.

    Parámetros
    ----------
    pdb_path     : str — ruta al PDB original
    chi_pred_deg : tensor [N, 4] — ángulos predichos en grados

    Retorna
    -------
    str — contenido del PDB modificado (para py3Dmol)
    """
    import io
    from Bio.PDB import PDBIO

    parser    = Bio.PDB.PDBParser(QUIET=True)
    structure = parser.get_structure("prot", pdb_path)

    residue_idx = 0
    for model_pdb in structure:
        for chain in model_pdb:
            for residue in sorted(chain.get_residues(), key=lambda r: r.get_id()[1]):
                if residue.get_id()[0] != ' ':
                    continue
                atom_names = {a.get_name() for a in residue}
                if not {'N', 'CA', 'C'}.issubset(atom_names):
                    continue
                if residue_idx >= chi_pred_deg.shape[0]:
                    break

                # Obtener el átomo Cγ (o equivalente) si existe
                gamma_names = ['CG', 'CG1', 'OG', 'SG', 'OG1']
                gamma_atom  = next(
                    (residue[a] for a in gamma_names if a in atom_names), None
                )

                if gamma_atom is not None and 'CB' in atom_names:
                    chi1_target = float(chi_pred_deg[residue_idx, 0])
                    ca_vec = residue['CA'].get_vector()
                    cb_vec = residue['CB'].get_vector()

                    # Calcular χ₁ actual
                    n_vec  = residue['N'].get_vector()
                    g_vec  = gamma_atom.get_vector()
                    chi1_current = Bio.PDB.calc_dihedral(n_vec, ca_vec, cb_vec, g_vec)
                    chi1_current_deg = np.degrees(chi1_current)

                    # Rotar el átomo Cγ la diferencia angular necesaria
                    delta = np.radians(chi1_target - chi1_current_deg)
                    axis  = (cb_vec - ca_vec).normalized()
                    rot   = Bio.PDB.rotaxis(delta, axis)
                    new_g_vec = (g_vec - cb_vec).left_multiply(rot) + cb_vec
                    gamma_atom.set_coord(new_g_vec.get_array())

                residue_idx += 1
        break

    # Serializar la estructura modificada a string PDB
    output = io.StringIO()
    io_obj = PDBIO()
    io_obj.set_structure(structure)
    io_obj.save(output)
    return output.getvalue()

